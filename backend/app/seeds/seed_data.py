# Helper to construct workout exercises with full ExerciseSchema embedded
def _make_workout_exercise(we_id: str, ex_dict: Dict[str, Any], sets_count: int, reps: int, weight: float, rest: int) -> Dict[str, Any]:
    return {
        "id": we_id,
        "exerciseId": ex_dict["id"],
        "exercise": ex_dict,
        "sets": [
            {
                "setNumber": i + 1,
                "targetReps": reps,
                "targetWeightKg": weight,
                "isCompleted": False,
            }
            for i in range(sets_count)
        ],
        "restSecondsBetweenSets": rest,
        "notes": f"{sets_count} sets of {reps} reps",
    }


def _get_ex(ex_id: str) -> Dict[str, Any]:
    for e in SEED_EXERCISES:
        if e["id"] == ex_id:
            return e
    return SEED_EXERCISES[0]


